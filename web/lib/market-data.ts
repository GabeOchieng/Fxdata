const rnd = (a: number, b: number) => Math.floor(Math.random() * (b - a + 1)) + a;
const rndF = (a: number, b: number) => parseFloat((a + Math.random() * (b - a)).toFixed(1));

// Build the live-ish dataset: random pro/job counts + a power-law XP so a few
// services are huge and most are small (the CryptoBubbles size distribution).
export function buildServiceData(): ServiceDatum[] {
  const data: ServiceDatum[] = RAW.map((r) => {
    const workers = rnd(5, 400), jobs = rnd(30, 3200), reviews = rnd(10, 1400);
    const rating = rndF(3.5, 5.0), growth = rndF(-12, 60);
    const rawXP = Math.pow(Math.random(), 1.8) * 10000;
    const communityXP = Math.min(10000, Math.floor(rawXP + workers * 8 + jobs * 0.8));
    return {
      ...r, workers, jobs, reviews, rating, growth, communityXP,
      level: getLevel(communityXP), color: CATS[r.cat]?.color ?? "#888", baseMultiplier: 0,
    };
  });
  const MIN_MULT = 0.42, MAX_MULT = 2.05, CURVE = 1.9;
  const sorted = data.slice().sort((a, b) => a.communityXP - b.communityXP);
  sorted.forEach((d, i) => {
    const pct = i / (sorted.length - 1);
    d.baseMultiplier = MIN_MULT + Math.pow(pct, CURVE) * (MAX_MULT - MIN_MULT);
  });
  return data;
}
